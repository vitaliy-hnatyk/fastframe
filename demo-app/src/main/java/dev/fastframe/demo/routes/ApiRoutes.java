package dev.fastframe.demo.routes;

import dev.fastframe.core.http.Response;
import dev.fastframe.core.http.Router;
import dev.fastframe.generated.FastFrameRoutes;

import java.util.concurrent.CompletableFuture;
import java.util.concurrent.Executor;

public final class ApiRoutes {
    private ApiRoutes() { }

    public static void register(Router router, Executor blockingExecutor) {
        // Global middleware must be installed before any route is registered.
        router.use((request, next) -> {
            if (request.path().startsWith("/api/") && request.header("x-demo-block") != null) {
                return CompletableFuture.completedFuture(Response.text("Forbidden by demo middleware").status(403));
            }
            return next.proceed(request).thenApply(response -> response.header("X-Framework", "FastFrame"));
        });
        router.get("/", request -> Response.text("FastFrame 0.6 on Netty"));
        router.get("/api/health", request -> Response.jsonValue(java.util.Map.of("status", "ok")));
        router.getAsync("/api/async-demo", request -> CompletableFuture.supplyAsync(
                () -> Response.jsonValue(java.util.Map.of("async", true)), blockingExecutor));
        // Routes and constructor dependency graph generated by the annotation processor.
        FastFrameRoutes.register(router);
    }
}

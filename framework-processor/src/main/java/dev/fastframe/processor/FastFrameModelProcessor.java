package dev.fastframe.processor;

import dev.fastframe.orm.annotation.Table;
import dev.fastframe.orm.annotation.Column;
import dev.fastframe.orm.annotation.Id;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.annotation.processing.SupportedSourceVersion;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.TypeMirror;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/** Generates type-safe record mappers; no reflection on query paths. */
@SupportedSourceVersion(SourceVersion.RELEASE_21)
@SupportedAnnotationTypes("dev.fastframe.orm.annotation.Table")
public final class FastFrameModelProcessor extends AbstractProcessor {
    private final Set<String> generated = new HashSet<>();
    @Override public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment round) {
        for (Element element : round.getElementsAnnotatedWith(Table.class)) {
            if (!(element instanceof TypeElement type)) continue;
            String qualified = type.getQualifiedName().toString();
            if (generated.add(qualified)) generate(type);
        }
        return true;
    }
    private void error(Element element, String msg) {
        processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, msg, element);
    }
    private static boolean ident(String v) { return v != null && v.matches("[A-Za-z_][A-Za-z_0-9]*"); }
    private void generate(TypeElement type) {
        if (type.getKind() != ElementKind.RECORD || !type.getModifiers().contains(Modifier.PUBLIC)
                || type.getNestingKind().isNested()) {
            error(type, "@Table requires a public top-level record"); return;
        }
        String table = type.getAnnotation(Table.class).value();
        for (String part : table.split("\\.", -1))
            if (!ident(part)) { error(type, "Invalid @Table SQL identifier"); return; }
        List<? extends RecordComponentElement> fields = type.getRecordComponents();
        if (fields.isEmpty()) { error(type, "Entity record needs an @Id component"); return; }
        RecordComponentElement id = null;
        Set<String> columns = new HashSet<>();
        String[] names = new String[fields.size()];
        for (int i = 0; i < fields.size(); i++) {
            RecordComponentElement field = fields.get(i);
            if (field.getAnnotation(Id.class) != null) {
                if (id != null) { error(type, "Exactly one @Id is allowed"); return; }
                id = field;
            }
            Column annotation = field.getAnnotation(Column.class);
            names[i] = annotation == null ? field.getSimpleName().toString() : annotation.value();
            if (!ident(names[i]) || !columns.add(names[i])) { error(field, "Invalid or duplicate @Column"); return; }
            if (valueExpression(field.asType().toString(), "r.get(\"" + names[i] + "\")") == null) {
                error(field, "Unsupported ORM component type " + field.asType()); return;
            }
        }
        if (id == null) { error(type, "A record component must be annotated @Id"); return; }
        String idType = boxed(id.asType().toString());
        if (!(idType.equals("java.lang.Long") || idType.equals("java.lang.Integer") || idType.equals("java.lang.String"))) {
            error(id, "@Id supports Long, Integer or String (or primitive long/int)"); return;
        }
        String idColumn = null;
        for (int i = 0; i < fields.size(); i++) if (fields.get(i).equals(id)) idColumn = names[i];
        String full = type.getQualifiedName().toString();
        int cut = full.lastIndexOf('.');
        String pkg = cut < 0 ? "" : full.substring(0, cut);
        String className = type.getSimpleName() + "FastFrameMapper";
        String generatedName = pkg.isBlank() ? className : pkg + "." + className;
        StringBuilder src = new StringBuilder();
        if (!pkg.isBlank()) src.append("package ").append(pkg).append(";\n");
        src.append("/** Generated by FastFrameModelProcessor. Do not edit. */\n");
        src.append("public final class ").append(className).append(" implements dev.fastframe.orm.EntityMapper<")
                .append(full).append(", ").append(idType).append("> {\n");
        src.append("  public String table() { return \"").append(table).append("\"; }\n");
        src.append("  public String idColumn() { return \"").append(idColumn).append("\"; }\n");
        src.append("  public ").append(idType).append(" id(").append(full).append(" entity) { return entity.")
                .append(id.getSimpleName()).append("(); }\n");
        src.append("  public java.util.Map<String,Object> toColumns(").append(full).append(" entity) {\n")
                .append("    java.util.Map<String,Object> row = new java.util.LinkedHashMap<>();\n");
        for (int i=0; i<fields.size(); i++) {
            src.append("    row.put(\"").append(names[i]).append("\", entity.")
               .append(fields.get(i).getSimpleName()).append("());\n");
        }
        src.append("    return row;\n  }\n");
        src.append("  public ").append(full).append(" fromRow(java.util.Map<String,Object> r) {\n    return new ")
           .append(full).append("(\n");
        for (int i=0; i<fields.size(); i++) {
            src.append("      ").append(valueExpression(fields.get(i).asType().toString(), "r.get(\""+names[i]+"\")"));
            src.append(i==fields.size()-1 ? "\n" : ",\n");
        }
        src.append("    );\n  }\n}\n");
        try (var writer = processingEnv.getFiler().createSourceFile(generatedName, type).openWriter()) {
            writer.write(src.toString());
        } catch (IOException ex) { error(type, "Failed generating ORM mapper: " + ex.getMessage()); }
    }
    private static String boxed(String type) {
        return switch(type) {
            case "long" -> "java.lang.Long";
            case "int" -> "java.lang.Integer";
            default -> type;
        };
    }
    private static String valueExpression(String type, String expr) {
        String num = "((java.lang.Number)" + expr + ")";
        return switch (type) {
            case "java.lang.String" -> "(java.lang.String)" + expr;
            case "long" -> num + ".longValue()";
            case "java.lang.Long" -> "(" + expr + " == null ? null : " + num + ".longValue())";
            case "int" -> num + ".intValue()";
            case "java.lang.Integer" -> "(" + expr + " == null ? null : " + num + ".intValue())";
            case "double" -> num + ".doubleValue()";
            case "java.lang.Double" -> "(" + expr + " == null ? null : " + num + ".doubleValue())";
            case "boolean" -> "((java.lang.Boolean)" + expr + ").booleanValue()";
            case "java.lang.Boolean" -> "(java.lang.Boolean)" + expr;
            case "java.math.BigDecimal" -> "(java.math.BigDecimal)" + expr;
            default -> null;
        };
    }
}
